"""Dependency locks of CodeGraph-Sci (corrective audit §8): exact versions for releases and CI.

- ``requirements.lock``: what the product runs and the portable folder redistributes (runtime dependencies, the
  ``view3d`` extra) with their own dependencies.
- ``requirements-dev.lock``: build and development tools (PyInstaller, the ``dev`` extra).

Usage:
    python tools/lock_dependencies.py --write    # regenerate both locks from the installed environment (offline)
    python tools/lock_dependencies.py --check    # verify the installed environment against the locks (exit 1)

Platform-specific dependencies keep the environment marker declared by the package that requires them. Hashes
(``pip install --require-hashes``) need the wheels of every platform from the package index: generate them on a
machine with network access, e.g. ``pip-compile --generate-hashes`` on these pins, as part of the release process;
the analysis itself never needs the network.
"""

from __future__ import annotations

import argparse
import re
import sys
from importlib.metadata import PackageNotFoundError, distribution
from pathlib import Path

from packaging.markers import Marker
from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parents[1]
RUNTIME_LOCK = ROOT / "requirements.lock"
DEV_LOCK = ROOT / "requirements-dev.lock"
HEADER = ("# Generated by tools/lock_dependencies.py from the reference environment (Python {py}); do not edit.\n"
          "# {what}\n")
LINUX = {"sys_platform": "linux", "platform_system": "Linux", "os_name": "posix"}
WINDOWS = {"sys_platform": "win32", "platform_system": "Windows", "os_name": "nt"}


def _canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _project_requirements() -> tuple[list[Requirement], list[Requirement]]:
    """(runtime + view3d, build + dev) requirements of pyproject.toml."""
    import tomllib

    data = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    project = data["project"]
    runtime = [Requirement(r) for r in project["dependencies"]]
    runtime += [Requirement(r) for r in project["optional-dependencies"].get("view3d", [])]
    dev = [Requirement(r) for r in project["optional-dependencies"].get("dev", [])] + [Requirement("pyinstaller")]
    return runtime, dev


def _closure(roots: list[Requirement], skip: set[str]) -> dict[str, tuple[str, str | None]]:
    """name -> (version, marker) for the installed closure of ``roots`` (markers kept for platform packages)."""
    out: dict[str, tuple[str, str | None]] = {}

    def visit(req: Requirement, marker: str | None) -> None:
        key = _canonical(req.name)
        if key in skip:
            return
        try:
            dist = distribution(req.name)
        except PackageNotFoundError:
            if marker is not None:  # a dependency of another platform
                out.setdefault(key, ("", marker))
                return
            raise SystemExit(f"error: {req.name} is required but not installed in this environment") from None
        known = out.get(key)
        if known is not None and (known[1] is None or known[1] == marker):
            return
        out[key] = (dist.version, marker if known is None else None)
        for raw in dist.requires or []:
            sub = Requirement(raw)
            if sub.marker is not None:
                text = str(sub.marker)
                if "extra" in text:
                    continue
                if not any(sub.marker.evaluate(env) for env in (LINUX, WINDOWS)):
                    continue
                both = all(sub.marker.evaluate(env) for env in (LINUX, WINDOWS))
                visit(sub, marker if both else text)
            else:
                visit(sub, marker)

    for root in roots:
        visit(root, str(root.marker) if root.marker else None)
    return out


def _render(pins: dict[str, tuple[str, str | None]], what: str) -> str:
    lines = [HEADER.format(py=".".join(map(str, sys.version_info[:3])), what=what)]
    for name in sorted(pins):
        version, marker = pins[name]
        if not version:
            lines.append(f"# {name}: required on another platform ({marker}); pin it from that platform\n")
            continue
        lines.append(f"{name}=={version}" + (f"; {marker}" if marker else "") + "\n")
    return "".join(lines)


def read_lock(path: Path) -> dict[str, tuple[str, Marker | None]]:
    pins: dict[str, tuple[str, Marker | None]] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        spec, _, marker = line.partition(";")
        name, _, version = spec.strip().partition("==")
        pins[_canonical(name)] = (version.strip(), Marker(marker.strip()) if marker.strip() else None)
    return pins


def check(paths: list[Path]) -> list[str]:
    """Differences between the installed environment and the locks (empty when they agree)."""
    problems = []
    for path in paths:
        for name, (version, marker) in sorted(read_lock(path).items()):
            if marker is not None and not marker.evaluate():
                continue
            try:
                installed = distribution(name).version
            except PackageNotFoundError:
                problems.append(f"{path.name}: {name}=={version} is not installed")
                continue
            if installed != version:
                problems.append(f"{path.name}: {name} {installed} installed, {version} locked")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--write", action="store_true", help="regenerate the locks from the installed environment")
    action.add_argument("--check", action="store_true", help="verify the installed environment against the locks")
    args = parser.parse_args()
    if args.write:
        runtime, dev = _project_requirements()
        runtime_pins = _closure(runtime, skip={"codegraph-sci"})
        dev_pins = _closure(dev, skip={"codegraph-sci"} | set(runtime_pins))
        RUNTIME_LOCK.write_text(_render(runtime_pins, "Runtime dependencies and the view3d extra (redistributed)."),
                                encoding="utf-8", newline="\n")
        DEV_LOCK.write_text(_render(dev_pins, "Build (PyInstaller) and development tools (dev extra)."),
                            encoding="utf-8", newline="\n")
        print(f"{RUNTIME_LOCK.name}: {len(runtime_pins)} pins, {DEV_LOCK.name}: {len(dev_pins)} pins")
        return 0
    problems = check([RUNTIME_LOCK, DEV_LOCK])
    for p in problems:
        print(p)
    print("environment matches the locks" if not problems else f"{len(problems)} difference(s)")
    return 0 if not problems else 1


if __name__ == "__main__":
    sys.exit(main())
